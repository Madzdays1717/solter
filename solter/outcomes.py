"""Passive decision journal; subsequent stream trades provide observations.

No market polling or Telegram messages are generated by this module. The
observed maximum is not an achievable execution price or realized profit.
"""

from dataclasses import dataclass
import time

from .events import Event


@dataclass
class Outcome:
    mint: str
    observed_at: float
    first_price_sol: float
    last_price_sol: float
    max_price_sol: float
    min_price_sol: float
    last_at: float
    status: str
    reason: str
    observed_trades: int = 0
    dirty: bool = True


class OutcomeJournal:
    HORIZON = 1800

    def __init__(self, storage):
        self.storage = storage
        self.states: dict[str, Outcome] = storage.load_outcomes()
        self.last_review: dict[str, tuple[str, str, float]] = {}
        self.events: list[tuple[str, float, str, str, float, float, float]] = []

    def review(self, mint: str, event: Event, status: str, reason: str,
               *, buy_sol: float = 0, sell_sol: float = 0) -> None:
        if event.price_sol <= 0:
            return
        now = time.time()
        entry = self.states.get(mint)
        if entry is None:
            entry = Outcome(mint, now, event.price_sol, event.price_sol,
                            event.price_sol, event.price_sol, event.timestamp,
                            status, reason)
            self.states[mint] = entry
        elif now - entry.observed_at > self.HORIZON:
            return
        last = self.last_review.get(mint)
        if last is None or (last[:2] != (status, reason) and now - last[2] >= 3) or now - last[2] >= 60:
            self.events.append((mint, now, status, reason, event.price_sol, buy_sol, sell_sol))
            self.last_review[mint] = (status, reason, now)
        entry.status = status
        entry.reason = reason
        entry.dirty = True

    def observe(self, event: Event):
        entry = self.states.get(event.mint)
        if not entry or not event.price_sol:
            return
        if event.timestamp < entry.observed_at or event.timestamp > entry.observed_at + self.HORIZON:
            return
        entry.last_price_sol = event.price_sol
        entry.last_at = event.timestamp
        entry.max_price_sol = max(entry.max_price_sol, event.price_sol)
        entry.min_price_sol = min(entry.min_price_sol, event.price_sol)
        entry.observed_trades += 1
        entry.dirty = True

    def flush(self):
        dirty = [entry for entry in self.states.values() if entry.dirty]
        if dirty or self.events:
            self.storage.save_outcomes(dirty, self.events)
            for entry in dirty:
                entry.dirty = False
            self.events.clear()
        cutoff = time.time() - self.HORIZON - 120
        for mint, entry in list(self.states.items()):
            if entry.observed_at < cutoff:
                del self.states[mint]
                self.last_review.pop(mint, None)
